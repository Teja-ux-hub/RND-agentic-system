import json
from typing import Any

from agents.utils import get_gemini_llm, LOGGER
from graph import AgentState, Strength, Weakness, Recommendation, Battlecard
from pydantic import BaseModel, Field


class SynthesisOutput(BaseModel):
    strengths: list[Strength] = Field(description="The company's key strengths")
    weaknesses: list[Weakness] = Field(description="The company's key weaknesses")
    market_trends: list[str] = Field(description="Key market trends affecting the company")
    actions: list[Recommendation] = Field(description="Actionable recommendations for the company")
    battlecard: Battlecard = Field(description="A sales battlecard for the company")


def _call_gemini_for_synthesis(company: str, evidence: list[dict]) -> dict[str, Any]:
    llm = get_gemini_llm(model_env_var="GEMINI_MODEL", default_model="gemini-2.0-flash", temperature=0.1)
    
    if not llm:
        return {
            "strengths": [],
            "weaknesses": [],
            "market_trends": [],
            "actions": [],
            "battlecard": {"strengths": [], "weaknesses": [], "win_themes": {}},
        }

    try:
        from langchain_core.prompts import ChatPromptTemplate

        prompt = ChatPromptTemplate.from_messages([
            ("system", "You are a world-class business strategist. Your goal is to synthesize raw evidence into actionable insights."),
            ("human", "Synthesize the following evidence for {company_name}:\n{evidence}")
        ])
        
        print(f"  > Calling Gemini for strategic synthesis ({company})...")
        structured_llm = llm.with_structured_output(SynthesisOutput)
        chain = prompt | structured_llm
        
        response = chain.invoke({"company_name": company, "evidence": json.dumps(evidence, ensure_ascii=True)})
        
        return {
            "strengths": [s.model_dump() for s in response.strengths],
            "weaknesses": [w.model_dump() for w in response.weaknesses],
            "market_trends": response.market_trends,
            "actions": [a.model_dump() for a in response.actions],
            "battlecard": response.battlecard.model_dump(),
        }
    except Exception as exc:  # pragma: no cover
        LOGGER.warning("SynthesisAgent analysis failed for %s: %s", company, exc)
        return {
            "strengths": [],
            "weaknesses": [],
            "market_trends": [],
            "actions": [],
            "battlecard": {"strengths": [], "weaknesses": [], "win_themes": {}},
        }


def run(state: AgentState) -> AgentState:
    """Synthesize raw intelligence into actionable strategic insights."""
    print(f"\n{'='*70}")
    print(f"🧠 [AGENT] SynthesisAgent - Strategic Intelligence Synthesis")
    print(f"{'='*70}")
    print(f"Analyzing data for: {state['company_name']}")
    LOGGER.info(f"SynthesisAgent: starting analysis for {state['company_name']}")
    LOGGER.debug("LLM Input (SynthesisAgent):\n%s", json.dumps(state["news_data"].get(state["company_name"], []), indent=2))

    print("  🤖 AI synthesis in progress: Converting data to strategic insights...")
    synthesis_result = _call_gemini_for_synthesis(state["company_name"], state["news_data"].get(state["company_name"], []))

    print(f"  ✅ Synthesis complete: {len(synthesis_result['strengths'])} strengths, {len(synthesis_result['weaknesses'])} weaknesses identified")
    print(f"  📈 Market trends: {len(synthesis_result['market_trends'])} key trends")
    print(f"  🎯 Actionable recommendations: {len(synthesis_result['actions'])} strategic actions")
    print(f"{'='*70}\n")

    LOGGER.debug("LLM Output (SynthesisAgent):\n%s", json.dumps(synthesis_result, indent=2))

    updated_state = dict(state)
    updated_state["strengths"] = synthesis_result["strengths"]
    updated_state["weaknesses"] = synthesis_result["weaknesses"]
    updated_state["market_trends"] = synthesis_result["market_trends"]
    updated_state["actions"] = synthesis_result["actions"]
    updated_state["battlecard"] = synthesis_result["battlecard"]
    # scoring_matrices and strategy_summary will be generated by StrategyAgent
    updated_state["scoring_matrices"] = state.get("scoring_matrices", {})
    updated_state["strategy_summary"] = state.get("strategy_summary", "")

    return updated_state
